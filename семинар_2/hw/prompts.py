def get_random_name(style, gender):
    """style: 'stereotype' или 'unique'
       gender: 'male' или 'female'"""
    if style == 'stereotype':
        if gender == 'male':
            return f"{random.choice(STEREOTYPE_FIRST_MALE)} {random.choice(STEREOTYPE_LAST_MALE)}"
        else:
            return f"{random.choice(STEREOTYPE_FIRST_FEMALE)} {random.choice(STEREOTYPE_LAST_FEMALE)}"
    else:  # unique
        if gender == 'male':
            return f"{random.choice(UNIQUE_FIRST_MALE)} {random.choice(UNIQUE_LAST_MALE)}"
        else:
            return f"{random.choice(UNIQUE_FIRST_FEMALE)} {random.choice(UNIQUE_LAST_FEMALE)}"

