"""
Планировщик: анализирует запрос и выбирает стратегию поиска.
"""

from llm_client import get_model, make_client
from schemas import MovieQuery, PlannerOutput


PLANNER_SYSTEM = """\
Ты — планировщик поиска фильмов по описанию сюжета.

Тебе дают запрос пользователя с описанием сюжета (иногда с подсказкой года или жанра).

Твоя задача — решить стратегию поиска:

1. **Оцени сложность запроса**:
   - Если описание очень детальное (много деталей, имён персонажей) → RAG с 5-7 чанками
   - Если описание общее (1-2 предложения) → RAG с 10-15 чанками
   - Если есть подсказка года/жанра → можно взять 5-7 чанков

2. **ВЕБ-ПОИСК ВСЕГДА ВКЛЮЧЁН для подтверждения**:
   - Даже если фильм кажется очевидным, веб-поиск нужен для проверки
   - Веб-поиск подтверждает название, год и сюжет из независимых источников
   - Без веб-поиска система может дать галлюцинацию (выдумать фильм)
   - Исключение: только если пользователь уже назвал точное название фильма

3. **Перефразируй запрос для веб-поиска**:
   - Добавь ключевые слова "фильм сюжет"
   - Если есть год — добавь его
   - Сделай запрос на русском

Правила:
- Минимум 3 чанка из RAG
- Максимум 20 чанков (ограничение контекста)
- Отвечай на РУССКОМ языке
"""


def planner(query: str, feedback: str | None = None) -> PlannerOutput:
    """Планировщик: возвращает стратегию поиска"""
    
    client = make_client()
    
    # Парсим запрос, чтобы понять, есть ли год/жанр
    import re
    year_match = re.search(r'\b(18[8-9]\d|19\d{2}|20[0-2]\d)\b', query)
    genre_words = ['боевик', 'комедия', 'драма', 'ужасы', 'фантастика', 'мелодрама', 
                   'приключения', 'триллер', 'детектив']
    has_genre = any(word in query.lower() for word in genre_words)
    
    messages = [
        {"role": "system", "content": PLANNER_SYSTEM},
        {"role": "user", "content": f"Запрос пользователя: {query}"}
    ]
    
    if feedback:
        messages.append({
            "role": "user", 
            "content": f"Предыдущая попытка не удалась: {feedback}. Предложи другую стратегию."
        })
    
    result = client.chat.completions.create(
        model=get_model(),
        messages=messages,
        response_model=PlannerOutput,
        temperature=0.0,
        max_retries=2,
        call_name="planner"
    )
    
    # Дополняем информацией о подсказках
    result.has_year_hint = year_match is not None
    result.has_genre_hint = has_genre
    
    return result