#!/bin/bash

# ============================================================
# Eval Script — полный запуск проекта (шаги 3-5)
# ============================================================
# 
# Запуск: ./eval.sh
# 
# Что делает:
#   3. Скачивает датасет с Kaggle (если нет)
#   4. Индексирует 3000 фильмов в RAG
#   5. Запускает eval на 3 фильмах: Матрица, Остров проклятых, Ведьма: Возрождение
# ============================================================

set -e  # Остановка при любой ошибке

# Цвета для вывода
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

echo ""
echo "============================================================"
echo "🎬 MOVIE QA SYSTEM — EVAL (шаги 3-5)"
echo "============================================================"
echo ""

# ============================================================
# 3. Скачивание датасета (если нет)
# ============================================================
echo -e "${BLUE}[3/5] Проверка датасета...${NC}"

if [ ! -f "input/movies.csv" ]; then
    echo "   📥 Скачиваем датасет с Kaggle..."
    python download_dataset.py
else
    echo -e "${GREEN}   ✅ Датасет уже есть: input/movies.csv${NC}"
fi
echo ""

# ============================================================
# 4. Индексация RAG (3000 фильмов)
# ============================================================
echo -e "${BLUE}[4/5] Индексация RAG (3000 фильмов)...${NC}"

# Проверяем, есть ли кэш
if [ -f "input/rag_cache.json" ]; then
    CACHE_SIZE=$(du -h input/rag_cache.json 2>/dev/null | cut -f1 || echo "неизвестно")
    echo -e "   📦 Кэш уже есть: input/rag_cache.json (${CACHE_SIZE})"
    echo "   🔄 Переиндексируем с 3000 фильмами..."
fi

python index_rag.py --max 3000 --force --no-summary

echo ""

# ============================================================
# 5. Запуск eval на 3 фильмах
# ============================================================
echo -e "${BLUE}[5/5] Запуск eval на 3 фильмах...${NC}"
echo ""

# Запускаем eval только на 3 тестах (Матрица, Ведьма: Возрождение, Остров проклятых)
python eval.py --ids 1 2 14

echo ""
echo "============================================================"
echo -e "${GREEN}✅ EVAL ЗАВЕРШЁН!${NC}"
echo "============================================================"
echo ""
echo "📁 Результаты:"
echo "   - eval:      output/eval_results.json"
echo "   - трейсы:    output/trace_*.json"
echo "   - кэш RAG:   input/rag_cache.json"
echo ""